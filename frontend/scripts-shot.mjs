import { chromium } from "@playwright/test";
const base = process.env.BASE || "http://127.0.0.1:8000";
const out = process.env.OUT || "/home/claude/shots";
const station = process.env.STATION || "Juvisy-sur-Orge";
const w = +(process.env.W || 1920), h = +(process.env.H || 1080);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: w, height: h } });
p.on("console", (m) => m.type() === "error" && console.log("console:", m.text()));
await p.goto(`${base}/#station=${encodeURIComponent(station)}`);
await p.waitForSelector(".section-svg", { timeout: 30000 });
await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/1-baseline-${w}.png` });
const lift = p.locator(".lift").filter({ hasText: "" }).nth(+(process.env.LIFT || 0));
await lift.click();
await p.waitForTimeout(300);
await p.getByRole("button", { name: "Simulate outage" }).click();
await p.waitForSelector(".banner.sim");
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/2-outage-${w}.png` });
await p.locator("button.cand").first().click();
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/3-repair-${w}.png` });
await p.locator(".pair.changed").first().click().catch(() => p.locator(".pair").first().click());
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/4-evidence-${w}.png`, fullPage: true });
await b.close();
